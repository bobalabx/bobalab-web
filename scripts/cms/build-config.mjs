#!/usr/bin/env node
/**
 * Generate the Decap CMS admin files from cms/ and the zod schema (WP6).
 *
 *   node scripts/cms/build-config.mjs            write public/admin/{config.yml, index.html,
 *                                                preview.css, fonts/*}
 *   node scripts/cms/build-config.mjs --check    exit 1 if any of them is out of date (CI)
 *   node scripts/cms/build-config.mjs --local    also write the local demo files
 *                                                public/admin/{config.local.yml, local.html}
 *                                                (git-ignored; used by scripts/cms/local.mjs)
 *   node scripts/cms/build-config.mjs --clean-local   remove the local demo files
 *   Local options: --site-url=http://localhost:3100  --proxy-url=http://localhost:8082/api/v1
 *   (a decap-server on another port, e.g. one serving a scratch copy of content/)
 *
 * Inputs: cms/source.mjs (labels, widgets, backend), cms/admin.html (page
 * template), cms/preview.css, src/styles/{tokens,base,prose,components}.css,
 * src/fonts/*.woff2 and src/lib/content/schema.ts (fields and constraints).
 * Output is deterministic: no timestamps, so unchanged inputs give identical files.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import * as prettier from "prettier";
import { stringify } from "yaml";
import { loadSchemaModule, loadTs } from "./lib/load-schema.mjs";
import { contentModels } from "./lib/zod-model.mjs";
import { adminCsp, allOrNothingRules, buildDecapConfig } from "./lib/decap-config.mjs";

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const ADMIN = "public/admin";
export const LOCAL_FILES = [`${ADMIN}/config.local.yml`, `${ADMIN}/local.html`];

const FONTS = [
  {
    file: "fraunces-latin-wght-normal.woff2",
    family: "Fraunces",
    weight: "100 900",
    variable: "--font-fraunces",
  },
  {
    file: "inter-latin-wght-normal.woff2",
    family: "Inter",
    weight: "100 900",
    variable: "--font-inter",
  },
  {
    file: "ibm-plex-mono-latin-500-normal.woff2",
    family: "IBM Plex Mono",
    weight: "500",
    variable: "--font-plex-mono",
  },
];
const STYLE_SOURCES = ["tokens.css", "base.css", "prose.css", "components.css"];

const YAML_OPTS = { lineWidth: 0, aliasDuplicateObjects: false };
const read = (rel) => fs.readFileSync(path.join(ROOT, rel), "utf8").replace(/\r\n/g, "\n");

const YAML_HEADER = (src) =>
  [
    "# GENERATED by scripts/cms/build-config.mjs. Do not edit by hand.",
    `# Source: cms/source.mjs (labels, widgets, backend) + src/lib/content/schema.ts (fields, constraints).`,
    "# Change the source, run `node scripts/cms/build-config.mjs`, commit both. tests/unit/cms checks parity.",
    ...(src ? [src] : []),
    "",
  ].join("\n");

export function buildPreviewCss() {
  const parts = [
    "/*",
    " * GENERATED by scripts/cms/build-config.mjs for the Decap preview pane",
    " * (CMS.registerPreviewStyle). Do not edit: the sources are",
    ` * src/styles/{${STYLE_SOURCES.join(",")}} and cms/preview.css.`,
    " */",
    "",
    "/* Fonts (SIL OFL-1.1, see fonts/OFL.txt): the site loads them through next/font. */",
    ...FONTS.map(
      (f) =>
        `@font-face {\n  font-family: "${f.family}";\n  src: url("fonts/${f.file}") format("woff2");\n  font-weight: ${f.weight};\n  font-style: normal;\n  font-display: swap;\n}`,
    ),
    `:root {\n${FONTS.map((f) => `  ${f.variable}: "${f.family}";`).join("\n")}\n}`,
    "",
  ];
  for (const s of STYLE_SOURCES) {
    parts.push(`/* ---- src/styles/${s} ---- */`, read(`src/styles/${s}`).trim(), "");
  }
  parts.push("/* ---- cms/preview.css ---- */", read("cms/preview.css").trim(), "");
  return parts.join("\n");
}

/**
 * public/admin/cms-data.js: data the browser-side scripts need, generated from
 * the site's own sources so it cannot drift:
 *  - labels: site wording and colours for preview-templates.js
 *    (src/components/ui/labels.ts, src/lib/content/people.ts, palette.ts);
 *  - rules enforced by cms-hooks.js: "all or nothing" optional objects (from
 *    the zod schema; see allOrNothingRules), file names of new entries,
 *    cross-field order, "required when …" and distinct-list rules (cms/source.mjs).
 */
export async function buildCmsData(models, source) {
  const labels = await loadTs("src/components/ui/labels.ts");
  const people = await loadTs("src/lib/content/people.ts");
  const palette = await loadTs("src/lib/content/palette.ts");
  const dates = await loadTs("src/lib/content/dates.ts");
  const schema = await loadSchemaModule();
  const data = {
    labels: {
      newsTypes: labels.NEWS_TYPE_LABELS,
      publicationTypes: labels.PUBLICATION_TYPE_LABELS,
      publicationStatus: labels.PUBLICATION_STATUS_LABELS,
      roles: Object.fromEntries(Object.entries(people.ROLE_LABELS).map(([k, v]) => [k, v.one])),
      swatches: Object.fromEntries(
        Object.values(palette.SWATCHES).map((w) => [
          w.id,
          { name: w.name, deep: w.deep, light: w.light, reserve: w.reserve },
        ]),
      ),
      confusablePairs: palette.CONFUSABLE_PAIRS,
      labTimeZone: dates.LAB_TIME_ZONE,
    },
    rules: {
      allOrNothing: allOrNothingRules(models, source),
      slugs: slugRules(source, schema.SLUG_PATTERNS),
      order: orderRules(models, source),
      required: requiredRules(models, source),
      unique: uniqueRules(models, source),
    },
  };
  return [
    "/* GENERATED by scripts/cms/build-config.mjs from src/components/ui/labels.ts,",
    " * src/lib/content/{people,palette,dates,schema}.ts and cms/source.mjs. Do not edit. */",
    `window.BOBALAB_CMS = ${JSON.stringify(data, null, 2)};`,
    "// Decap starts only after our hooks and previews are registered (cms-start.js).",
    "window.CMS_MANUAL_INIT = true;",
    "",
  ].join("\n");
}

/**
 * File-name rules for new entries (cms-hooks.js slugProblem): each folder
 * collection's Decap `slug` template and identifier field (cms/source.mjs) with
 * the schema's SLUG_PATTERNS (pattern, hint, max length) for that collection.
 */
export function slugRules(source, patterns) {
  const out = {};
  for (const c of source.collections) {
    const p = patterns[c.name];
    if (!p) throw new Error(`collection ${c.name}: no SLUG_PATTERNS entry in the schema`);
    out[c.name] = {
      template: c.slug,
      identifier: c.identifier_field,
      pattern: p.re.source,
      hint: p.hint,
      max: p.max,
    };
  }
  return out;
}

/** Cross-field "not before" rules (cms/source.mjs orderRules), checked against the models. */
export function orderRules(models, source) {
  return (source.orderRules ?? []).map((r) => {
    const model = models[r.scope];
    if (!model) throw new Error(`orderRules: unknown scope ${r.scope}`);
    for (const f of [r.earlier, r.later])
      if (!model.fields.some((x) => x.name === f))
        throw new Error(`orderRules: ${r.scope} has no field ${f}`);
    return { scope: r.scope, earlier: r.earlier, later: r.later, labels: r.labels };
  });
}

/** The zod model of a rule scope: a folder collection or "<file collection>/<file>". */
function modelOfScope(models, source, scope) {
  if (!scope.includes("/")) return models[scope];
  const [fc, file] = scope.split("/");
  const f = source.fileCollections.find((c) => c.name === fc)?.files.find((x) => x.name === file);
  return f ? models[f.schema] : undefined;
}

/** The node at a dotted path ("links.pdf", "presentations.*.url") of an object model. */
export function nodeAtPath(model, dotted) {
  let node = model;
  for (const part of dotted.split(".")) {
    if (part === "*") {
      if (node?.kind !== "array") return undefined;
      node = node.items;
      continue;
    }
    if (node?.kind !== "object") return undefined;
    node = node.fields.find((x) => x.name === part)?.node;
  }
  return node;
}

/**
 * "Required when …" rules (cms/source.mjs requiredRules) for cms-hooks.js, each
 * path checked against the schema, and every enum value in a condition too.
 */
export function requiredRules(models, source) {
  return (source.requiredRules ?? []).map((r, i) => {
    const where = `requiredRules[${i}] (${r.code})`;
    const model = modelOfScope(models, source, r.scope);
    if (!model) throw new Error(`${where}: unknown scope ${r.scope}`);
    const target = nodeAtPath(model, r.field);
    if (!target) throw new Error(`${where}: ${r.scope} has no field ${r.field}`);
    if (r.min != null && target.kind !== "array")
      throw new Error(`${where}: min is for lists, ${r.field} is ${target.kind}`);
    for (const c of r.when ?? []) {
      const node = nodeAtPath(model, c.field);
      if (!node) throw new Error(`${where}: ${r.scope} has no field ${c.field}`);
      const values = c.in ?? c.notIn;
      if (!Array.isArray(values) || (c.in && c.notIn))
        throw new Error(`${where}: a condition needs exactly one of in / notIn`);
      if (node.kind === "enum")
        for (const v of values)
          if (!node.values.includes(v))
            throw new Error(`${where}: ${c.field} has no value ${JSON.stringify(v)}`);
    }
    for (const p of r.anySet ?? [])
      if (!nodeAtPath(model, p)) throw new Error(`${where}: ${r.scope} has no field ${p}`);
    if (!r.message) throw new Error(`${where}: needs a message`);
    return {
      code: r.code,
      scope: r.scope,
      field: r.field,
      ...(r.min != null ? { min: r.min } : {}),
      when: (r.when ?? []).map((c) =>
        c.in ? { field: c.field, in: c.in } : { field: c.field, notIn: c.notIn },
      ),
      anySet: r.anySet ?? [],
      message: r.message,
    };
  });
}

/** Lists whose items must be distinct (cms/source.mjs uniqueRules). */
export function uniqueRules(models, source) {
  return (source.uniqueRules ?? []).map((r) => {
    const model = modelOfScope(models, source, r.scope);
    if (!model) throw new Error(`uniqueRules: unknown scope ${r.scope}`);
    if (nodeAtPath(model, r.field)?.kind !== "array")
      throw new Error(`uniqueRules: ${r.scope}.${r.field} is not a list`);
    return { code: r.code, scope: r.scope, field: r.field, label: r.label };
  });
}

/**
 * The CMS login-screen logo: the lab wordmark as a standalone SVG, from the same
 * outlined geometry as src/components/brand/Wordmark.tsx (ink on Decap's light UI).
 */
export async function buildLogoSvg() {
  const { WORDMARK } = await loadTs("src/components/brand/wordmark-geometry.ts");
  const [, , vw, vh] = WORDMARK.viewBox;
  const P = WORDMARK.pearl;
  const r = P.r * 0.68;
  const pt = (deg) => [
    P.cx + r * Math.cos((deg * Math.PI) / 180),
    P.cy + r * Math.sin((deg * Math.PI) / 180),
  ];
  const [x0, y0] = pt(200);
  const [x1, y1] = pt(252);
  const crescent = `M${x0.toFixed(2)} ${y0.toFixed(2)}A${r.toFixed(2)} ${r.toFixed(2)} 0 0 1 ${x1.toFixed(2)} ${y1.toFixed(2)}`;
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${vw} ${vh}" width="${vw}" height="${vh}" role="img" aria-label="BOBALAB">`,
    "<!-- GENERATED by scripts/cms/build-config.mjs from src/components/brand/wordmark-geometry.ts -->",
    "<title>BOBALAB</title>",
    `<g fill="#1F1712">`,
    ...WORDMARK.boba.map((d) => `<path d="${d}"/>`),
    `<circle cx="${P.cx}" cy="${P.cy}" r="${P.r}" fill="#2B1D15"/>`,
    ...WORDMARK.lab.map((d) => `<path d="${d}"/>`),
    "</g>",
    `<path d="${crescent}" fill="none" stroke="#F7F1E8" stroke-opacity=".25" stroke-width="${(P.r * 0.13).toFixed(2)}" stroke-linecap="round"/>`,
    "</svg>",
    "",
  ].join("\n");
}

function adminHtml(source, decapVersion, { local, proxyOrigin }) {
  return read("cms/admin.html")
    .replace(
      "%GENERATED%",
      local
        ? "GENERATED local demo page (git-ignored). Do not commit or edit."
        : "GENERATED by scripts/cms/build-config.mjs. Do not edit by hand.",
    )
    .replace("%DECAP_VERSION%", decapVersion)
    .replace("%CSP%", adminCsp(source, { local, extraConnect: proxyOrigin ? [proxyOrigin] : [] }))
    .replace(
      "%TITLE%",
      local ? "Content manager (local demo) · BOBALAB" : "Content manager · BOBALAB",
    )
    .replace("%CONFIG%", local ? "config.local.yml" : "config.yml");
}

/**
 * Every generated file: { "public/admin/x": string | Buffer }.
 * @param {{ local?: boolean, localSiteUrl?: string, proxyUrl?: string }} [opts]
 */
export async function generate(opts = {}) {
  const schema = await loadSchemaModule();
  const source = await import(pathToFileURL(path.join(ROOT, "cms", "source.mjs")).href);
  const models = contentModels(schema);
  const lock = JSON.parse(read("cms/decap-cms.lock.json"));
  const out = {};
  const prod = buildDecapConfig(models, source, { mode: "production" });
  out[`${ADMIN}/config.yml`] = YAML_HEADER() + stringify(prod, YAML_OPTS);
  out[`${ADMIN}/index.html`] = adminHtml(source, lock.version, { local: false });
  out[`${ADMIN}/preview.css`] = buildPreviewCss();
  out[`${ADMIN}/cms-data.js`] = await buildCmsData(models, source);
  out[`${ADMIN}/logo.svg`] = await buildLogoSvg();
  for (const f of FONTS)
    out[`${ADMIN}/fonts/${f.file}`] = fs.readFileSync(path.join(ROOT, "src", "fonts", f.file));
  out[`${ADMIN}/fonts/OFL.txt`] = read("src/fonts/OFL.txt");
  if (opts.local) {
    const loc = buildDecapConfig(models, source, {
      mode: "local",
      localSiteUrl: opts.localSiteUrl,
      proxyUrl: opts.proxyUrl,
    });
    out[`${ADMIN}/config.local.yml`] =
      YAML_HEADER("# LOCAL DEMO CONFIG (git-ignored): decap-server proxy, simple publish mode.") +
      stringify(loc, YAML_OPTS);
    out[`${ADMIN}/local.html`] = adminHtml(source, lock.version, {
      local: true,
      proxyOrigin: opts.proxyUrl ? new URL(opts.proxyUrl).origin : undefined,
    });
  }
  // Format like the rest of the repo, so `prettier --check .` passes on generated files.
  for (const [rel, content] of Object.entries(out)) {
    if (typeof content === "string") out[rel] = await pretty(rel, content);
  }
  return out;
}

async function pretty(rel, text) {
  const abs = path.join(ROOT, rel);
  const info = await prettier.getFileInfo(abs, { ignorePath: path.join(ROOT, ".prettierignore") });
  if (info.ignored || !info.inferredParser) return text;
  const options = (await prettier.resolveConfig(abs)) ?? {};
  return prettier.format(text, { ...options, filepath: abs });
}

function same(abs, content) {
  if (!fs.existsSync(abs)) return false;
  const cur = fs.readFileSync(abs);
  return Buffer.isBuffer(content) ? cur.equals(content) : cur.toString("utf8") === content;
}

async function main() {
  const args = process.argv.slice(2);
  if (args.includes("--clean-local")) {
    for (const rel of LOCAL_FILES) fs.rmSync(path.join(ROOT, rel), { force: true });
    console.log("[cms] removed local demo files");
    return;
  }
  const check = args.includes("--check");
  const arg = (name) => {
    const a = args.find((x) => x.startsWith(`--${name}=`));
    return a ? a.slice(name.length + 3) : undefined;
  };
  const files = await generate({
    local: args.includes("--local"),
    localSiteUrl: arg("site-url"),
    proxyUrl: arg("proxy-url"),
  });
  const stale = [];
  for (const [rel, content] of Object.entries(files)) {
    const abs = path.join(ROOT, rel);
    if (same(abs, content)) continue;
    if (check) stale.push(rel);
    else {
      fs.mkdirSync(path.dirname(abs), { recursive: true });
      fs.writeFileSync(abs, content);
      console.log(`[cms] wrote ${rel}`);
    }
  }
  if (check && stale.length) {
    console.error(
      `[cms] out of date (run node scripts/cms/build-config.mjs):\n  ${stale.join("\n  ")}`,
    );
    process.exitCode = 1;
  } else if (check) console.log("[cms] generated admin files are up to date");
  else console.log("[cms] admin files up to date");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((e) => {
    console.error(`[cms] ${e.message}`);
    process.exit(1);
  });
}
